"""Emits Rust consts for the GUIDs and *_VER macros in nvEncodeAPI.h."""
import re
import sys

src = open(sys.argv[1]).read()
major = int(re.search(r"#define NVENCAPI_MAJOR_VERSION (\d+)", src).group(1))
minor = int(re.search(r"#define NVENCAPI_MINOR_VERSION (\d+)", src).group(1))
api_version = major | (minor << 24)

print("// Generated by gen_consts.py from nvEncodeAPI.h. Do not edit.")
print("use crate::GUID;")
print()

ver_re = re.compile(
    r"#define (\w+_VER)\s+\(?NVENCAPI_STRUCT_VERSION\((\d+)\)\s*(\|\s*\(\s*1\s*<<\s*31\s*\))?\)?"
)
for name, ver, high in ver_re.findall(src):
    value = api_version | (int(ver) << 16) | (0x7 << 28)
    if high:
        value |= 1 << 31
    print(f"pub const {name}: u32 = {value:#010x};")
print()

guid_re = re.compile(
    r"static const GUID\s+(\w+)\s*=\s*\{\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*\{([^}]*)\}\s*\};"
)
count = 0
for name, d1, d2, d3, d4 in guid_re.findall(src):
    bytes_ = ", ".join(b.strip() for b in d4.split(","))
    print(
        f"pub const {name}: GUID = GUID {{ Data1: {d1}, Data2: {d2}, Data3: {d3}, Data4: [{bytes_}] }};"
    )
    count += 1
assert count == src.count("static const GUID"), "missed a GUID"
