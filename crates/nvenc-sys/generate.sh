#!/bin/sh
# Regenerates src/bindings.rs from include/nvEncodeAPI.h (NVIDIA Video Codec
# SDK 12.1, MIT licensed). Requires bindgen-cli and libclang.
#
# Enums are newtypes, not Rust enums, so an unknown value from a newer
# driver is not undefined behavior.
#
# The header is parsed without _WIN32: every NVENC struct uses fixed-width
# integers and pointers only, so the x86_64 SysV and Windows x64 layouts are
# identical (bindgen's layout tests check this on both CI targets). The one
# Windows-only difference, NVENC_RECT vs RECT, is four 32-bit fields either way.
set -eu
cd "$(dirname "$0")"
bindgen \
    --allowlist-type 'NVENC.*' \
    --allowlist-type 'NV_ENC.*' \
    --allowlist-type 'NV_ENCODE.*' \
    --allowlist-type 'GUID' \
    --allowlist-type 'PNVENC.*' \
    --allowlist-var 'NVENC.*' \
    --allowlist-var 'NV_ENC.*' \
    --allowlist-var 'NV_MAX.*' \
    --blocklist-item 'NV_ENC_\w+_GUID' \
    --default-enum-style=newtype \
    --no-doc-comments \
    --with-derive-default \
    --use-core \
    --merge-extern-blocks \
    --sort-semantically \
    --raw-line '// Generated by bindgen from include/nvEncodeAPI.h. Do not edit.' \
    --raw-line '// Derived from nvEncodeAPI.h, Copyright (c) 2010-2023 NVIDIA Corporation, MIT license (notice in the header).' \
    --raw-line '#![allow(non_upper_case_globals, non_camel_case_types, non_snake_case, dead_code, clippy::all)]' \
    --output src/bindings.rs \
    include/nvEncodeAPI.h -- -x c

# GUIDs are `static const` and struct versions are function-like macros, which
# bindgen skips; extract them with a small script instead.
python3 gen_consts.py include/nvEncodeAPI.h > src/consts.rs
rustfmt --edition 2024 src/bindings.rs src/consts.rs
